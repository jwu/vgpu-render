/**
 * GPU renderer for the 2D debug-draw layer.
 *
 * The 2D primitives are the 3D ones under a different projection. `camera-2d.ts` produces a clip
 * matrix that lands `world2d`/`screen` pixels on the near plane, and the line, point and joint
 * shaders already do everything after the projection in screen space — pixel widths, dash phase,
 * joint wedges, the near-plane clip. So this renderer reuses that WGSL verbatim (injected as
 * `shaders`, because the 3D renderer owns the source and must not be imported back) and only
 * supplies its own instance buffers, indirect draws and camera uniforms.
 *
 * `world2d` and `screen` commands need different matrices, and one draw binds one uniform, so each
 * space gets its own bucket of primitives. The layer draws after every 3D primitive with depth
 * write off, which is what makes the 2D overlay unconditionally cover the 3D world.
 */

import { compute, draw, geometry, storage, type Compute, type Draw, type FrameComputePass, type FramePass, type Gpu, type StorageBuffer } from "vgpu";
import { prepareShader } from "@vgpu/wgsl/prepare";

import { instanceGeometry, type InstanceGeometry } from "vgpu/scene/gpu";
import { instances, type InstanceCollection, type InstanceId } from "vgpu/scene";
import { DEFAULT_CAMERA_2D, projection2D, type Camera2D, type Space2D, type Vec2 } from "./camera-2d.js";
import type { FrameCommand2D, Joint2DCommand, Line2DCommand, Point2DCommand, Shape2DCommand, Shape2DKind } from "./frame-recorder-2d.js";
import { identity, indirectArgs, INDIRECT_SHADER, trim, world, zeroGeometry } from "./gpu-instancing.js";
import { shape2dShader } from "./shape2d-shader.js";

export type GpuDebugDraw2DOptions = {
  /**
   * WGSL for the shared primitives, generated by `GpuDebugDraw3D` so the two layers cannot drift
   * apart on the instance layout. The vertex stages must place the primitive through
   * `camera.viewProjection * vec4f(position, 1.0)` and read `camera.viewportSize`.
   */
  readonly shaders: {
    readonly point: string;
    readonly line: string;
    readonly joint: string;
  };
  /** Vertices the injected joint shader fans out per wedge; must match its `ROUND_RESOLUTION`. */
  readonly jointVertexCount: number;
  readonly points?: number;
  readonly lines?: number;
  readonly joints?: number;
  readonly shapes?: number;
};

type PointCollection2D = InstanceCollection<{
  point: "float32x3";
  color: "float32x4";
  size: "float32";
  flags: "uint32";
}>;
type LineCollection2D = InstanceCollection<{
  start: "float32x3";
  end: "float32x3";
  color: "float32x4";
  colorEnd: "float32x4";
  width: "float32";
  flags: "uint32";
  dash: "float32x3";
  normal: "float32x3";
  joint: "uint32";
}>;
type JointCollection2D = InstanceCollection<{
  previous: "float32x3";
  center: "float32x3";
  next: "float32x3";
  color: "float32x4";
  width: "float32";
  flags: "uint32";
  dash: "float32x3";
  joint: "uint32";
  previousNormal: "float32x3";
  nextNormal: "float32x3";
}>;

type ShapeCollection2D = InstanceCollection<{
  shape: "uint32";
  center: "float32x3";
  size: "float32x2";
  vertexB: "float32x2";
  vertexC: "float32x2";
  params: "float32x4";
  /** (rotation, bounding radius); packed because the vertex stage only has 16 attribute slots. */
  rotationRadius: "float32x2";
  color: "float32x4";
  /** bit0: filled; bits 8..15: polygon vertex count. */
  flags: "uint32";
}>;

/** Must match the `SHAPE_*` constants in `shape2d-shader.ts`. */
const SHAPE2D_CODES: Readonly<Record<Shape2DKind, number>> = {
  "rect": 0,
  "rounded-rect": 1,
  "circle": 2,
  "ellipse": 3,
  "arc": 4,
  "annulus": 5,
  "capsule": 6,
  "polygon": 7,
  "triangle": 8,
  "rhombus": 9,
  "sector": 10,
  "segment": 11,
};

/** One view matrix, shared by every 2D draw: the layer never applies the back-face normal fade. */
const IDENTITY_VIEW = identity();

const ZERO_NORMAL: Vec3Like = [0, 0, 0];
type Vec3Like = readonly [number, number, number];

function sameVec2(a: Vec2, b: Vec2): boolean {
  return a[0] === b[0] && a[1] === b[1];
}
function sameColor(a: readonly [number, number, number, number], b: readonly [number, number, number, number]): boolean {
  return a[0] === b[0] && a[1] === b[1] && a[2] === b[2] && a[3] === b[3];
}
function samePoint2D(a: Point2DCommand, b: Point2DCommand): boolean {
  return sameVec2(a.position, b.position) && sameColor(a.color, b.color) && a.size === b.size && a.sizeMode === b.sizeMode && a.round === b.round;
}
function sameLine2D(a: Line2DCommand, b: Line2DCommand): boolean {
  return (
    sameVec2(a.start, b.start) &&
    sameVec2(a.end, b.end) &&
    sameColor(a.color, b.color) &&
    sameColor(a.colorEnd, b.colorEnd) &&
    a.width === b.width &&
    a.widthMode === b.widthMode &&
    a.dash?.[0] === b.dash?.[0] &&
    a.dash?.[1] === b.dash?.[1] &&
    a.dash?.[2] === b.dash?.[2] &&
    a.joint === b.joint
  );
}
function sameJoint2D(a: Joint2DCommand, b: Joint2DCommand): boolean {
  return (
    sameVec2(a.previous, b.previous) &&
    sameVec2(a.center, b.center) &&
    sameVec2(a.next, b.next) &&
    sameColor(a.color, b.color) &&
    a.width === b.width &&
    a.widthMode === b.widthMode &&
    a.joint === b.joint &&
    a.dash?.[0] === b.dash?.[0] &&
    a.dash?.[1] === b.dash?.[1] &&
    a.dash?.[2] === b.dash?.[2]
  );
}
function sameShape2D(a: Shape2DCommand, b: Shape2DCommand): boolean {
  return (
    a.shape === b.shape &&
    sameVec2(a.center, b.center) &&
    sameVec2(a.size, b.size) &&
    sameVec2(a.vertexB, b.vertexB) &&
    sameVec2(a.vertexC, b.vertexC) &&
    a.cornerRadius === b.cornerRadius &&
    a.thickness === b.thickness &&
    a.filled === b.filled &&
    a.rotation === b.rotation &&
    a.startAngle === b.startAngle &&
    a.sweep === b.sweep &&
    a.sides === b.sides &&
    sameColor(a.color, b.color)
  );
}

/** Two-dimensional point lifted onto the near plane the projection matrix maps to. */
function lift2D(point: Vec2): Vec3Like {
  return [point[0], point[1], 0];
}

/** Circle that bounds the shape at any rotation: the instanced quad's extent in shape space. */
function boundingRadius(command: Shape2DCommand): number {
  const [x, y] = command.size;
  switch (command.shape) {
    case "rect":
    case "rounded-rect":
    case "rhombus":
      return Math.hypot(x, y);
    case "ellipse":
      return Math.max(x, y);
    case "capsule":
      return y + x;
    case "triangle": {
      const corners = [command.size, command.vertexB, command.vertexC];
      return Math.max(...corners.map((corner) => Math.hypot(corner[0], corner[1])));
    }
    default:
      // circle, arc, annulus (x is the outer radius), polygon, sector and segment.
      return x;
  }
}

function jointGeometry(gpu: Gpu, vertexCount: number) {
  return geometry(gpu, {
    buffers: [{ attributes: { position: "float32x3" }, data: new Float32Array(vertexCount * 3) }],
    vertexCount,
    topology: "triangle-list",
  });
}

/**
 * The primitives of one 2D space. Separate instance collections from the 3D layer, because one
 * draw binds one camera uniform and both layers can be visible in the same frame.
 */
class SpaceBucket2D {
  readonly space: Space2D;
  readonly #points: PointCollection2D;
  readonly #lines: LineCollection2D;
  readonly #joints: JointCollection2D;
  readonly #shapes: ShapeCollection2D;
  readonly #pointIds: InstanceId[] = [];
  readonly #lineIds: InstanceId[] = [];
  readonly #jointIds: InstanceId[] = [];
  readonly #shapeIds: InstanceId[] = [];
  readonly #pointCache: Point2DCommand[] = [];
  readonly #lineCache: Line2DCommand[] = [];
  readonly #jointCache: Joint2DCommand[] = [];
  readonly #shapeCache: Shape2DCommand[] = [];
  readonly #pointBridge: InstanceGeometry;
  readonly #lineBridge: InstanceGeometry;
  readonly #jointBridge: InstanceGeometry;
  readonly #shapeBridge: InstanceGeometry;
  readonly #pointDraw: Draw;
  readonly #lineDraw: Draw;
  readonly #jointDraw: Draw;
  readonly #shapeDraw: Draw;
  readonly #pointIndirect: StorageBuffer;
  readonly #lineIndirect: StorageBuffer;
  readonly #jointIndirect: StorageBuffer;
  readonly #shapeIndirect: StorageBuffer;
  readonly #indirectCompute: Compute;
  readonly #jointVertexCount: number;
  #pointCount = 0;
  #lineCount = 0;
  #jointCount = 0;
  #shapeCount = 0;
  #pointDirty = true;
  #lineDirty = true;
  #jointDirty = true;
  #shapeDirty = true;

  constructor(gpu: Gpu, space: Space2D, options: GpuDebugDraw2DOptions, capacities: { points: number; lines: number; joints: number; shapes: number }) {
    this.space = space;
    this.#jointVertexCount = options.jointVertexCount;
    this.#points = instances({ capacity: capacities.points, attributes: { point: "float32x3", color: "float32x4", size: "float32", flags: "uint32" } });
    this.#lines = instances({ capacity: capacities.lines, attributes: { start: "float32x3", end: "float32x3", color: "float32x4", colorEnd: "float32x4", width: "float32", flags: "uint32", dash: "float32x3", normal: "float32x3", joint: "uint32" } });
    this.#joints = instances({ capacity: capacities.joints, attributes: { previous: "float32x3", center: "float32x3", next: "float32x3", color: "float32x4", width: "float32", flags: "uint32", dash: "float32x3", joint: "uint32", previousNormal: "float32x3", nextNormal: "float32x3" } });
    this.#shapes = instances({ capacity: capacities.shapes, attributes: { shape: "uint32", center: "float32x3", size: "float32x2", vertexB: "float32x2", vertexC: "float32x2", params: "float32x4", rotationRadius: "float32x2", color: "float32x4", flags: "uint32" } });
    this.#pointBridge = instanceGeometry(gpu, this.#points, { mesh: zeroGeometry(gpu) });
    this.#lineBridge = instanceGeometry(gpu, this.#lines, { mesh: zeroGeometry(gpu) });
    this.#jointBridge = instanceGeometry(gpu, this.#joints, { mesh: jointGeometry(gpu, options.jointVertexCount) });
    this.#shapeBridge = instanceGeometry(gpu, this.#shapes, { mesh: zeroGeometry(gpu) });
    // No depth write: the 2D layer is an overlay, and the projection puts it on the near plane
    // where a "less-equal" test against anything the 3D layer drew succeeds.
    const depth = { write: false, compare: "less-equal" } as const;
    this.#pointDraw = draw(gpu, { shader: prepareShader(options.shaders.point), geometry: this.#pointBridge.geometry, instances: 0, blend: "alpha", cull: "none", depth });
    this.#lineDraw = draw(gpu, { shader: prepareShader(options.shaders.line), geometry: this.#lineBridge.geometry, instances: 0, blend: "alpha", cull: "none", depth });
    this.#jointDraw = draw(gpu, { shader: prepareShader(options.shaders.joint), geometry: this.#jointBridge.geometry, instances: 0, blend: "alpha", cull: "none", depth });
    this.#shapeDraw = draw(gpu, { shader: prepareShader(shape2dShader()), geometry: this.#shapeBridge.geometry, instances: 0, blend: "alpha", cull: "none", depth });
    this.#pointIndirect = storage(gpu, 16, { access: "read-write", indirect: true });
    this.#lineIndirect = storage(gpu, 16, { access: "read-write", indirect: true });
    this.#jointIndirect = storage(gpu, 16, { access: "read-write", indirect: true });
    this.#shapeIndirect = storage(gpu, 16, { access: "read-write", indirect: true });
    this.#indirectCompute = compute(gpu, INDIRECT_SHADER);
    indirectArgs(this.#pointIndirect, 6, 0);
    indirectArgs(this.#lineIndirect, 6, 0);
    indirectArgs(this.#jointIndirect, options.jointVertexCount, 0);
    indirectArgs(this.#shapeIndirect, 6, 0);
  }

  prepare(points: readonly Point2DCommand[], lines: readonly Line2DCommand[], joints: readonly Joint2DCommand[], shapes: readonly Shape2DCommand[]): void {
    this.#pointDirty = false;
    this.#lineDirty = false;
    this.#jointDirty = false;
    this.#shapeDirty = false;
    for (let index = 0; index < points.length; index++) this.#addPoint(points[index]!, index);
    for (let index = 0; index < lines.length; index++) this.#addLine(lines[index]!, index);
    for (let index = 0; index < joints.length; index++) this.#addJoint(joints[index]!, index);
    for (let index = 0; index < shapes.length; index++) this.#addShape(shapes[index]!, index);
    if (trim(this.#points, this.#pointIds, points.length)) this.#pointDirty = true;
    if (trim(this.#lines, this.#lineIds, lines.length)) this.#lineDirty = true;
    if (trim(this.#joints, this.#jointIds, joints.length)) this.#jointDirty = true;
    if (trim(this.#shapes, this.#shapeIds, shapes.length)) this.#shapeDirty = true;
    if (this.#pointCache.length !== points.length) this.#pointDirty = true;
    if (this.#lineCache.length !== lines.length) this.#lineDirty = true;
    if (this.#jointCache.length !== joints.length) this.#jointDirty = true;
    if (this.#shapeCache.length !== shapes.length) this.#shapeDirty = true;
    this.#pointCache.length = points.length;
    this.#lineCache.length = lines.length;
    this.#jointCache.length = joints.length;
    this.#shapeCache.length = shapes.length;
    if (this.#pointDirty) {
      this.#pointCount = this.#pointBridge.publish();
      indirectArgs(this.#pointIndirect, 6, this.#pointCount);
    }
    if (this.#lineDirty) {
      this.#lineCount = this.#lineBridge.publish();
      indirectArgs(this.#lineIndirect, 6, this.#lineCount);
    }
    if (this.#jointDirty) {
      this.#jointCount = this.#jointBridge.publish();
      indirectArgs(this.#jointIndirect, this.#jointVertexCount, this.#jointCount);
    }
    if (this.#shapeDirty) {
      this.#shapeCount = this.#shapeBridge.publish();
      indirectArgs(this.#shapeIndirect, 6, this.#shapeCount);
    }
  }

  dispatchIndirect(pass: FrameComputePass): void {
    this.#indirectCompute.set({ params: { vertexCount: 6, instanceCount: this.#pointCount }, args: this.#pointIndirect });
    pass.dispatch(this.#indirectCompute, 1);
    this.#indirectCompute.set({ params: { vertexCount: 6, instanceCount: this.#lineCount }, args: this.#lineIndirect });
    pass.dispatch(this.#indirectCompute, 1);
    this.#indirectCompute.set({ params: { vertexCount: this.#jointVertexCount, instanceCount: this.#jointCount }, args: this.#jointIndirect });
    pass.dispatch(this.#indirectCompute, 1);
    this.#indirectCompute.set({ params: { vertexCount: 6, instanceCount: this.#shapeCount }, args: this.#shapeIndirect });
    pass.dispatch(this.#indirectCompute, 1);
  }

  draw(pass: FramePass, camera: Camera2D): void {
    if (this.#pointCount === 0 && this.#lineCount === 0 && this.#jointCount === 0 && this.#shapeCount === 0) return;
    const viewportSize = pass.target.size;
    const viewProjection = projection2D(this.space, camera, viewportSize);
    // Filled shapes first, then strokes, then points and joints: the layer reads as a filled
    // backdrop with its outlines and markers drawn over it.
    if (this.#shapeCount > 0) {
      this.#shapeDraw.set({
        camera: {
          viewProjection,
          viewportSize,
          yFlip: this.space === "screen" ? 1 : -1,
          pixelsPerUnit: this.space === "screen" ? 1 : camera.zoom,
        },
      });
      pass.draw(this.#shapeDraw, { indirect: this.#shapeIndirect });
    }
    if (this.#pointCount > 0) {
      this.#pointDraw.set({ camera: { viewProjection, viewportSize } });
      pass.draw(this.#pointDraw, { indirect: this.#pointIndirect });
    }
    if (this.#lineCount > 0) {
      this.#lineDraw.set({ camera: { viewProjection, view: IDENTITY_VIEW, viewportSize } });
      pass.draw(this.#lineDraw, { indirect: this.#lineIndirect });
    }
    if (this.#jointCount > 0) {
      this.#jointDraw.set({ camera: { viewProjection, view: IDENTITY_VIEW, viewportSize } });
      pass.draw(this.#jointDraw, { indirect: this.#jointIndirect });
    }
  }

  destroy(): void {
    this.#pointDraw.dispose();
    this.#lineDraw.dispose();
    this.#jointDraw.dispose();
    this.#shapeDraw.dispose();
    this.#indirectCompute.dispose();
    this.#pointBridge.destroy();
    this.#lineBridge.destroy();
    this.#jointBridge.destroy();
    this.#shapeBridge.destroy();
  }

  get count(): number {
    return this.#pointCount + this.#lineCount + this.#jointCount + this.#shapeCount;
  }

  #addPoint(command: Point2DCommand, index: number): void {
    const previous = this.#pointCache[index];
    this.#pointCache[index] = command;
    if (previous !== undefined && samePoint2D(previous, command)) return;
    this.#pointDirty = true;
    const id = this.#pointIds[index] ?? this.#addPointId(index);
    this.#points.set(id, {
      point: lift2D(command.position),
      color: command.color,
      size: command.size,
      flags: (command.sizeMode === "world" ? 1 : 0) | (command.round ? 2 : 0),
    });
  }

  #addPointId(index: number): InstanceId {
    const id = this.#points.add({ point: [0, 0, 0], color: [0, 0, 0, 0], size: 0, flags: 0 });
    world(this.#points, id);
    this.#pointIds[index] = id;
    return id;
  }

  #addLine(command: Line2DCommand, index: number): void {
    const previous = this.#lineCache[index];
    this.#lineCache[index] = command;
    if (previous !== undefined && sameLine2D(previous, command)) return;
    this.#lineDirty = true;
    const id = this.#lineIds[index] ?? this.#addLineId(index);
    const dash = command.dash ?? [0, 0, 0];
    const joint = command.joint === "round" ? 1 : command.joint === "bevel" ? 2 : command.joint === "miter" ? 3 : 0;
    this.#lines.set(id, {
      start: lift2D(command.start),
      end: lift2D(command.end),
      color: command.color,
      colorEnd: command.colorEnd,
      width: command.width,
      flags: command.widthMode === "world" ? 1 : 0,
      dash,
      normal: ZERO_NORMAL,
      joint,
    });
  }

  #addLineId(index: number): InstanceId {
    const id = this.#lines.add({ start: [0, 0, 0], end: [0, 0, 0], color: [0, 0, 0, 0], colorEnd: [0, 0, 0, 0], width: 0, flags: 0, dash: [0, 0, 0], normal: [0, 0, 0], joint: 0 });
    world(this.#lines, id);
    this.#lineIds[index] = id;
    return id;
  }

  #addJoint(command: Joint2DCommand, index: number): void {
    const previous = this.#jointCache[index];
    this.#jointCache[index] = command;
    if (previous !== undefined && sameJoint2D(previous, command)) return;
    this.#jointDirty = true;
    const id = this.#jointIds[index] ?? this.#addJointId(index);
    this.#joints.set(id, {
      previous: lift2D(command.previous),
      center: lift2D(command.center),
      next: lift2D(command.next),
      color: command.color,
      width: command.width,
      flags: command.widthMode === "world" ? 1 : 0,
      dash: command.dash ?? [0, 0, 0],
      joint: command.joint === "round" ? 1 : command.joint === "bevel" ? 2 : 3,
      previousNormal: ZERO_NORMAL,
      nextNormal: ZERO_NORMAL,
    });
  }

  #addJointId(index: number): InstanceId {
    const id = this.#joints.add({ previous: [0, 0, 0], center: [0, 0, 0], next: [0, 0, 0], color: [0, 0, 0, 0], width: 0, flags: 0, dash: [0, 0, 0], joint: 0, previousNormal: [0, 0, 0], nextNormal: [0, 0, 0] });
    world(this.#joints, id);
    this.#jointIds[index] = id;
    return id;
  }

  #addShape(command: Shape2DCommand, index: number): void {
    const previous = this.#shapeCache[index];
    this.#shapeCache[index] = command;
    if (previous !== undefined && sameShape2D(previous, command)) return;
    this.#shapeDirty = true;
    const id = this.#shapeIds[index] ?? this.#addShapeId(index);
    this.#shapes.set(id, {
      shape: SHAPE2D_CODES[command.shape],
      center: lift2D(command.center),
      size: command.size,
      vertexB: command.vertexB,
      vertexC: command.vertexC,
      params: [command.cornerRadius, command.thickness, command.startAngle, command.sweep],
      rotationRadius: [command.rotation, boundingRadius(command)],
      color: command.color,
      flags: (command.filled ? 1 : 0) | (command.sides << 8),
    });
  }

  #addShapeId(index: number): InstanceId {
    const id = this.#shapes.add({ shape: 0, center: [0, 0, 0], size: [0, 0], vertexB: [0, 0], vertexC: [0, 0], params: [0, 0, 0, 0], rotationRadius: [0, 0], color: [0, 0, 0, 0], flags: 0 });
    world(this.#shapes, id);
    this.#shapeIds[index] = id;
    return id;
  }
}

export class GpuDebugDraw2D {
  readonly #buckets: Record<Space2D, SpaceBucket2D>;
  #camera: Camera2D = DEFAULT_CAMERA_2D;

  constructor(gpu: Gpu, options: GpuDebugDraw2DOptions) {
    const capacities = {
      points: options.points ?? 4096,
      lines: options.lines ?? 16384,
      joints: options.joints ?? 8192,
      shapes: options.shapes ?? 8192,
    };
    this.#buckets = {
      world2d: new SpaceBucket2D(gpu, "world2d", options, capacities),
      screen: new SpaceBucket2D(gpu, "screen", options, capacities),
    };
  }

  /** Camera the `world2d` bucket projects through. `screen` commands ignore it. */
  setCamera(camera: Camera2D): void {
    this.#camera = { pan: [camera.pan[0], camera.pan[1]], zoom: camera.zoom };
  }

  get camera(): Camera2D {
    return this.#camera;
  }

  prepare(commands: readonly FrameCommand2D[]): void {
    const points: Record<Space2D, Point2DCommand[]> = { world2d: [], screen: [] };
    const lines: Record<Space2D, Line2DCommand[]> = { world2d: [], screen: [] };
    const joints: Record<Space2D, Joint2DCommand[]> = { world2d: [], screen: [] };
    const shapes: Record<Space2D, Shape2DCommand[]> = { world2d: [], screen: [] };
    for (const command of commands) {
      if (command.kind === "point2d") points[command.space].push(command);
      else if (command.kind === "line2d") lines[command.space].push(command);
      else if (command.kind === "shape2d") shapes[command.space].push(command);
      else joints[command.space].push(command);
    }
    // Both buckets are refreshed every frame, empty or not: that is what drops the previous
    // frame's primitives instead of leaving them on screen.
    this.#buckets.world2d.prepare(points.world2d, lines.world2d, joints.world2d, shapes.world2d);
    this.#buckets.screen.prepare(points.screen, lines.screen, joints.screen, shapes.screen);
  }

  dispatchIndirect(pass: FrameComputePass): void {
    this.#buckets.world2d.dispatchIndirect(pass);
    this.#buckets.screen.dispatchIndirect(pass);
  }

  draw(pass: FramePass): void {
    this.#buckets.world2d.draw(pass, this.#camera);
    this.#buckets.screen.draw(pass, this.#camera);
  }

  destroy(): void {
    this.#buckets.world2d.destroy();
    this.#buckets.screen.destroy();
  }

  /** Instances the last `prepare` left in both buckets, for tests and status readouts. */
  get primitiveCount(): number {
    return this.#buckets.world2d.count + this.#buckets.screen.count;
  }
}
