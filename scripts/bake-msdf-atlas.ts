// Bake the bundled face into a prebuilt multi-channel distance field atlas.
//
// Usage:
//   bun scripts/bake-msdf-atlas.ts
//
// The on-demand encoder in `src/text-msdf-font.ts` runs `msdfFromOutline` the first time each glyph
// is drawn, which also means linking `opentype.js`. Baking moves that work to build time and inlines
// the result, so a consumer pays neither. The trade is a fixed character set and a payload that ships
// whether or not it is used — which is exactly why both routes exist.
//
// The page travels gzipped and base64'd rather than as a PNG: WebGPU wants raw texels, every target
// already has `DecompressionStream`, and no image decoder has to run — which is what keeps the
// payload loadable in Node, where the tests run.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { gzipSync } from "node:zlib";
import { GlyphAtlas } from "../src/text-atlas.js";
import { resolveFontFace } from "../src/text-layout.js";
import { OutlineGlyphRasterizer } from "../src/text-msdf-font.js";

const ROOT = resolve(import.meta.dir, "..");
const TARGET = resolve(ROOT, "src/assets/fira-mono-msdf-atlas.ts");

/** Rasterisation size of the baked fields. Larger costs payload; smaller blurs when magnified. */
const BAKE_SIZE = 24;
const PAGE_SIZE = 512;
/** Matches `DEFAULT_FONT_FAMILY`; only used as the atlas cache key during the bake. */
const FONT_FAMILY = "vgpu-render-fira-mono";
const FACE = resolveFontFace({ family: FONT_FAMILY });
const DISTANCE_RANGE = 4;

/** The same blocks the inlined font subset covers. */
const RANGES: readonly (readonly [number, number])[] = [
  [0x20, 0x7e],
  [0xa0, 0xff],
  [0x100, 0x17f],
  [0x370, 0x3ff],
  [0x2000, 0x206f],
  [0x2070, 0x209f],
  [0x2100, 0x214f],
  [0x2190, 0x21ff],
  [0x2200, 0x22ff],
  [0x25a0, 0x25ff],
  [0x2600, 0x26ff],
];

const rounded = (value: number, digits: number): number => Number(value.toFixed(digits));

const rasterizer = new OutlineGlyphRasterizer({ distanceRange: DISTANCE_RANGE });
const atlas = new GlyphAtlas(rasterizer, { size: PAGE_SIZE, maxPages: 1 });

/** `[u0, v0, u1, v1, bearingLeft, bearingTop, width, height, advance]`, all at `BAKE_SIZE`. */
const glyphs: Record<string, readonly number[]> = {};
let baked = 0;
for (const [low, high] of RANGES) {
  for (let code = low; code <= high; code++) {
    const character = String.fromCodePoint(code);
    const metrics = rasterizer.glyphMetrics(character, FACE, BAKE_SIZE);
    const entry = atlas.glyph(character, FACE, BAKE_SIZE);
    // Whitespace has no ink box but still advances the pen, and layout is driven entirely by these
    // numbers: a character left out of the table would collapse the spaces between words.
    const uv = entry === undefined ? [0, 0, 0, 0] : entry.uv.map((value) => rounded(value, 6));
    glyphs[character] = [
      ...uv,
      rounded(metrics.bearingLeft, 3),
      rounded(metrics.bearingTop, 3),
      rounded(metrics.width, 3),
      rounded(metrics.height, 3),
      rounded(metrics.advance, 3),
    ];
    if (entry !== undefined) baked++;
  }
}

const page = atlas.pages[0];
if (page === undefined) throw new Error("the bake produced no atlas page");

const vertical = rasterizer.verticalMetrics(FACE, BAKE_SIZE);

const compressed = gzipSync(page.data, { level: 9 });
const base64 = compressed.toString("base64");
const lines: string[] = [];
for (let index = 0; index < base64.length; index += 96) lines.push(`  "${base64.slice(index, index + 96)}",`);

const glyphLines = Object.entries(glyphs)
  .map(([character, values]) => `  ${JSON.stringify(character)}: [${values.join(", ")}],`)
  .join("\n");

const source = `// Generated by \`bun scripts/bake-msdf-atlas.ts\`. Do not edit by hand.
//
// A prebaked multi-channel signed distance field for the bundled Fira Mono subset (${baked} glyphs,
// ${BAKE_SIZE} px raster, ${PAGE_SIZE}² page), so a consumer can draw text without linking
// \`opentype.js\` or running the encoder. See \`src/assets/fonts/README.md\` for how to regenerate it.

/** Edge of the square page, in texels. */
export const BAKED_MSDF_PAGE_SIZE = ${PAGE_SIZE};
/** Font size the fields were rasterised at. All glyph metrics are expressed at this size. */
export const BAKED_MSDF_BAKE_SIZE = ${BAKE_SIZE};
/** Distance, in texels, the field covers either side of the edge. */
export const BAKED_MSDF_DISTANCE_RANGE = ${DISTANCE_RANGE};
/** Ascent and descent of the face at the bake size, so layout never has to re-read the font. */
export const BAKED_MSDF_ASCENT = ${rounded(vertical.ascent, 3)};
export const BAKED_MSDF_DESCENT = ${rounded(vertical.descent, 3)};

/** Gzipped RGBA8 page, base64 encoded. */
export const BAKED_MSDF_PAGE_GZIP_BASE64 = [
${lines.join("\n")}
].join("");

/** Per glyph: \`[u0, v0, u1, v1, bearingLeft, bearingTop, width, height, advance]\` at the bake size. */
export const BAKED_MSDF_GLYPHS: Readonly<Record<string, readonly number[]>> = {
${glyphLines}
};
`;

writeFileSync(TARGET, source);
console.log(`baked ${baked} glyphs into a ${PAGE_SIZE}² page`);
console.log(`raw ${(page.data.byteLength / 1024 / 1024).toFixed(2)} MiB -> gzip ${(compressed.byteLength / 1024).toFixed(0)} KiB`);
console.log(`wrote ${TARGET} (${(source.length / 1024).toFixed(0)} KiB)`);
