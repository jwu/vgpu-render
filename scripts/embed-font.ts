// Embed the bundled default font into a TypeScript module.
//
// Usage:
//   bun scripts/embed-font.ts
//
// The library inlines its default font the way bevy inlines its own with
// `include_bytes!` (crates/bevy_text/src/lib.rs), so a consumer never has to
// fetch, host or register a font asset at runtime.
//
// Two payloads of the same subset are embedded, because the two glyph pipelines
// need different containers:
//   - WOFF2 feeds `FontFace`, which Canvas2D rasterises for the bitmap and SDF
//     encodings. It is the compact one.
//   - TrueType feeds `opentype.js`, which reads outlines for the MSDF encoder and
//     cannot decompress WOFF2.
//
// The generated module is plain base64 with no bundler-specific import, so tests
// and any TypeScript toolchain can read it without an asset pipeline. Source bytes
// stay in `src/assets/fonts/` for auditing and licence tracking;
// `tests/font-asset.test.ts` asserts the generated constants match them.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const FONT_DIR = resolve(ROOT, "src/assets/fonts");
const TARGET = resolve(ROOT, "src/assets/fira-mono-medium-subset.ts");
const LINE_WIDTH = 96;

const payloads = [
  {
    file: "fira-mono-medium-subset.woff2",
    constant: "FIRA_MONO_MEDIUM_SUBSET_BASE64",
    doc: "WOFF2 bytes of the bundled default font, base64 encoded. Feed it to `FontFace`.",
  },
  {
    file: "fira-mono-medium-subset.ttf",
    constant: "FIRA_MONO_MEDIUM_SUBSET_TTF_BASE64",
    doc: "TrueType bytes of the same subset, base64 encoded. `opentype.js` reads outlines from this one.",
  },
];

const banner = `// Generated by \`bun scripts/embed-font.ts\`. Do not edit by hand.
//
// Fira Mono Medium, subset to ASCII, Latin-1 Supplement, Latin Extended-A, Greek,
// General Punctuation, sub/superscripts, letterlike symbols, arrows, mathematical
// operators, geometric shapes and miscellaneous symbols. Licensed under the SIL Open
// Font License 1.1; see \`src/assets/fonts/FiraMono-LICENSE.txt\` and
// \`src/assets/fonts/README.md\` for provenance and how to regenerate this file.`;

const sections = payloads.map(({ file, constant, doc }) => {
  const base64 = readFileSync(resolve(FONT_DIR, file)).toString("base64");
  const lines: string[] = [];
  for (let index = 0; index < base64.length; index += LINE_WIDTH) {
    lines.push(base64.slice(index, index + LINE_WIDTH));
  }
  console.log(`embedded ${file}: ${base64.length} base64 chars (${lines.length} lines)`);
  return `/** ${doc} */\nexport const ${constant} = [\n${lines.map((line) => `  "${line}",`).join("\n")}\n].join("");`;
});

writeFileSync(TARGET, `${banner}\n\n${sections.join("\n\n")}\n`);
console.log(`wrote ${TARGET}`);
