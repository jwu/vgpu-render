// Builds the multi-weight sans family the font-query page needs.
//
// Usage:
//   bun scripts/build-font-faces.ts
//
// Canvas2D cannot touch a variable font's axes: it has no `font-variation-settings`, and the shorthand
// only carries one synthesised bold step. What it *does* do is pick a face by its `weight` descriptor,
// so a variable font becomes nine real weights by being instanced into static faces and registered
// under one family. This script does the build half — instantiate, rename, subset — and inlines the
// result, the same way `embed-font.ts` inlines the debug font.
//
// The source is the variable font the reference `font-query` example uses. It is OFL with the reserved
// name "Mona", so every instance is renamed: a modified copy may not keep that name.

import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const TARGET = resolve(ROOT, "src/assets/vgpu-sans-faces.ts");
const SOURCE = process.env.MONA_SANS_SOURCE
  ?? resolve(homedir(), "src/bevy@bevyengine/assets/fonts/MonaSans-VariableFont.ttf");

/**
 * Mona Sans ships `wght` 200–900, so there is no 100. The page's weight column lists exactly these:
 * a row for 100 would draw the 200 instance, which is the "row that never changes" this rebuild is
 * meant to remove.
 */
const WEIGHTS: readonly number[] = [200, 300, 400, 500, 600, 700, 800, 900];

/** Latin plus the punctuation the page's labels use (middle dot, dashes, ellipsis). */
const UNICODES = "U+0020-007E,U+00B7,U+2013-2014,U+2026";

/** Renames a static instance. `updateFontNames=False` keeps the variable font's own naming, so this
 * has to run afterwards and cover every name a font menu would read. */
const RENAME_SCRIPT = `
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

source, weight, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
font = TTFont(source)
instance = instantiateVariableFont(font, {"wght": weight}, updateFontNames=False)
for record in instance["name"].names:
    if record.nameID in (1, 3, 4, 6, 16, 17, 21, 22):
        value = record.toUnicode()
        value = value.replace("Mona Sans", "vgpu-render Sans").replace("MonaSans", "vgpu-renderSans")
        record.string = value
instance.save(out)
`;

function run(command: string, args: readonly string[]): void {
  const result = spawnSync(command, args, { stdio: ["ignore", "pipe", "pipe"], encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed:\n${result.stderr || result.stdout}`);
  }
}

const work = mkdtempSync(resolve(tmpdir(), "vgpu-sans-"));
const renameScript = resolve(work, "rename.py");
writeFileSync(renameScript, RENAME_SCRIPT);

const faces: { weight: number; base64: string }[] = [];
for (const weight of WEIGHTS) {
  const instanceTtf = resolve(work, `vgpu-sans-${weight}.ttf`);
  const subsetWoff2 = resolve(work, `vgpu-sans-${weight}.woff2`);
  run("uv", ["run", "--with", "fonttools", "python", renameScript, SOURCE, String(weight), instanceTtf]);
  run("uv", [
    "run", "--with", "fonttools", "--with", "brotli", "python", "-m", "fontTools.subset", instanceTtf,
    `--unicodes=${UNICODES}`, "--no-hinting", "--no-glyph-names",
    `--output-file=${subsetWoff2}`, "--flavor=woff2",
  ]);
  faces.push({ weight, base64: readFileSync(subsetWoff2).toString("base64") });
  console.log(`instanced ${weight}: ${(readFileSync(subsetWoff2).byteLength / 1024).toFixed(1)} KiB`);
}

const bytes = faces.reduce((total, face) => total + face.base64.length, 0);
const source = `/**
 * Multi-weight sans family for the font-query page. **Generated by \`bun scripts/build-font-faces.ts\`**
 * — edit that script, not this file.
 *
 * Each entry is one static instance of the source variable font, subset to the Latin blocks the page's
 * labels use. Canvas2D selects a face by its \`weight\` descriptor, so registering all of them under one
 * family is what makes eight distinct weights drawable at all (see \`loadFontFaces\`).
 *
 * Source: Mona Sans (SIL OFL 1.1, reserved name "Mona"), instanced and renamed to
 * "${"vgpu-render Sans"}". The licence is next to the debug font in \`src/assets/fonts/\`.
 */

/** One instanced face: the weight it was built at, and its WOFF2 container. */
export type EmbeddedSansFace = {
  readonly weight: number;
  readonly woff2Base64: string;
};

/** The weights the build produced, ascending. */
export const VGPU_SANS_WEIGHTS: readonly number[] = [${WEIGHTS.join(", ")}];

export const VGPU_SANS_FACES: readonly EmbeddedSansFace[] = [
${faces.map((face) => `  { weight: ${face.weight}, woff2Base64: "${face.base64}" },`).join("\n")}
];
`;

writeFileSync(TARGET, source);
console.log(`wrote ${TARGET} (${(bytes / 1024).toFixed(0)} KiB of base64, ${faces.length} faces)`);
